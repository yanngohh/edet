// ---------------------------------------------------------------- the pin ----

interface Vector {
    name: string;
    tx: Tx;
    nonce: number[];
    not_after_epoch: number;
    digest: string;
}

describe('the digest this device signs', () => {
    it('matches the node on every transaction in the alphabet', () => {
        for (const v of RUST_TX_DIGESTS as Vector[]) {
            expect(toHex(txDigestLocal(RUST_CHAIN_ID, v.tx, v.nonce, v.not_after_epoch)), v.name).toBe(v.digest);
        }
    });

    /** Every variant, so a new transaction cannot arrive unpinned. */
    it('covers the whole alphabet', () => {
        const names = new Set((RUST_TX_DIGESTS as Vector[]).map((v) => Object.keys(v.tx)[0]));
        expect(names.size).toBe(20);
    });

    /**
     * The chain id is length-prefixed into the preimage, and this is why:
     * without the prefix, one chain id followed by a payload can be spelled as
     * a different chain id followed by a different payload.
     */
    it('binds the signature to one chain', () => {
        const v = (RUST_TX_DIGESTS as Vector[])[0];
        const other = toHex(txDigestLocal(RUST_CHAIN_ID + 'x', v.tx, v.nonce, v.not_after_epoch));
        expect(other).not.toBe(v.digest);
    });

    /** And to one envelope: the nonce and the window are both covered. */
    it('binds the signature to one envelope', () => {
        const v = (RUST_TX_DIGESTS as Vector[])[0];
        const nonce = [...v.nonce];
        nonce[0] ^= 1;
        expect(toHex(txDigestLocal(RUST_CHAIN_ID, v.tx, nonce, v.not_after_epoch))).not.toBe(v.digest);
        expect(toHex(txDigestLocal(RUST_CHAIN_ID, v.tx, v.nonce, v.not_after_epoch + 1))).not.toBe(v.digest);
    });

    /**
     * **A panel is a SET, so the order a member clicked in is not part of it.**
     *
     * `ArbTerms.arbiters` is a `BTreeSet<MemberId>` on the ledger, so its
     * encoding is ascending — and the generated vectors cannot catch a client
     * that forgot that, because `serde_json` serialises the set already
     * sorted, so the fixture arrives in the order the encoder wants. Measured:
     * deleting the sort in `txdigest.ts` leaves every vector above green. This
     * is the probe that goes red for it.
     */
    it('orders an arbitration panel the way the ledger does, not the way it was typed', () => {
        const v = (RUST_TX_DIGESTS as Vector[]).find((x) => x.name === 'accept_with_arb')!;
        const accept = (v.tx as Extract<Tx, { Accept: unknown }>).Accept;
        const shuffled: Tx = {
            Accept: { ...accept, arb: { ...accept.arb!, arbiters: [...accept.arb!.arbiters].reverse() } },
        };
        expect(accept.arb!.arbiters.length, 'the fixture needs a panel to reorder').toBeGreaterThan(1);
        expect(toHex(txDigestLocal(RUST_CHAIN_ID, shuffled, v.nonce, v.not_after_epoch))).toBe(v.digest);
    });

    /**
     * **It refuses rather than falling back.** A transaction this encoder
     * cannot represent is one this device must not sign — and asking the node
     * for the digest instead is precisely the hole being closed, so there is
     * no such path to take.
     */
    it('refuses what it cannot encode exactly', () => {
        const unknown = { NotATransaction: { member: 1 } } as unknown as Tx;
        expect(() => txDigestLocal('c', unknown, new Array(16).fill(0), 1)).toThrow(TxEncodeError);
        const huge = { Exit: { member: Number.MAX_SAFE_INTEGER + 2 } } as Tx;
        expect(() => txDigestLocal('c', huge, new Array(16).fill(0), 1)).toThrow(TxEncodeError);
        const shortNonce = { Exit: { member: 1 } } as Tx;
        expect(() => txDigestLocal('c', shortNonce, [1, 2, 3], 1)).toThrow(TxEncodeError);
    });
});
