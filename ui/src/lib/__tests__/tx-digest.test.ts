/**
 * The client's own signing digest, pinned to the node's.
 *
 * **This is what lets the wallet stop signing whatever a node hands it.** Until
 * a wallet that fetched the payload from `/tx/digest` and signed the reply —
 * or co-signed a pending entry by signing `entry.digest`, a hex string the same
 * node served, with nothing checking that it corresponded to the `entry.tx`
 * shown on screen — would let a node the member had been talked into adding
 * under `custom` answer with the digest of a different envelope and collect a
 * valid signature over it.
 *
 * Computing it here means a second implementation of a canonical encoding, and
 * two implementations drift. So the vectors below are GENERATED by the
 * normative one — `cargo run -p edet-node --features serve --example
 * tx_digest_fixture` — and `just tx-digest-check` fails on any drift, the same
 * shape as `proof-fixture-check`. A cross-pin whose oracle is hand-copied is
 * pinned to whatever was last pasted.
 */

